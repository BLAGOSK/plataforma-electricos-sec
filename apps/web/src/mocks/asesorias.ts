/** Fecha relativa a hoy a una hora local dada. */
function enDias(dias: number, hora = 10, minuto = 0): string {
  const d = new Date();
  d.setDate(d.getDate() + dias);
  d.setHours(hora, minuto, 0, 0);
  return d.toISOString();
}

